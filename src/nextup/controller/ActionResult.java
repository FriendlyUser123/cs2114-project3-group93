package nextup.controller;

/**
 * OWNER: Ha Minh Nguyen. The outcome of one user action: did it work, and
 * what message should the view print. Views check isOk() and print
 * getMessage(), so they never see a model exception.
 *
 * Built with the two static factory methods, never with new:
 *
 * <pre>
 * return ActionResult.ok("You're #4. Your ticket is 4821.");
 * return ActionResult.fail("Wrong PIN");
 * </pre>
 *
 * @author Ha Minh Nguyen
 * @version 2026.11.13
 */
public class ActionResult {

    private final boolean ok;
    private final String message;

    /**
     * Private: use ok(...) or fail(...).
     *
     * @param ok
     *            whether the action worked
     * @param message
     *            the message to show
     * @throws IllegalArgumentException
     *             if message is null
     */
    private ActionResult(boolean ok, String message) {
        if (message == null) {
            throw new IllegalArgumentException("Message must not be null.");
        }
        this.ok = ok;
        this.message = message;
    }


    /**
     * Creates a successful result.
     *
     * @param message
     *            the message to show
     * @return the result
     * @throws IllegalArgumentException
     *             if message is null
     */
    public static ActionResult ok(String message) {
        return new ActionResult(true, message);
    }


    /**
     * Creates a failed result.
     *
     * @param message
     *            the message to show
     * @return the result
     * @throws IllegalArgumentException
     *             if message is null
     */
    public static ActionResult fail(String message) {
        return new ActionResult(false, message);
    }


    /**
     * Returns whether the action worked.
     *
     * @return true if it worked
     */
    public boolean isOk() {
        return ok;
    }


    /**
     * Returns the message to show the user.
     *
     * @return the message; never null
     */
    public String getMessage() {
        return message;
    }
}