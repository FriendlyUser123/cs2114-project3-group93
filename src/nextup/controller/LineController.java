package nextup.controller;

import nextup.model.LineRuleException;
import nextup.model.OfficeHoursLine;

/**
 * OWNER: Ha Minh Nguyen. Carries user actions from the views to the model,
 * checks TA mode, and turns every outcome into an ActionResult.
 *
 * Rules for this class (from the D2 spec):
 * <ul>
 * <li>Line rules (blank names, duplicates, full line, ...) are NOT checked
 * here. Call the model and catch LineRuleException:
 *
 * <pre>
 * try {
 *     int ticket = model.join(name, question);
 *     int position = model.positionOf(ticket);
 *     return ActionResult.ok(
 *         "You're #" + position + ". Your ticket is " + ticket + ".");
 * }
 * catch (LineRuleException e) {
 *     return ActionResult.fail(e.getMessage());
 * }
 * </pre>
 *
 * </li>
 * <li>This class DOES own: turning ticket text into an int, the TA PIN, and
 * TA mode ("who is at the keyboard" is about the session, not the line).
 * </li>
 * <li>Never print here, and never import nextup.view.</li>
 * </ul>
 *
 * Exact messages to use: "Enter your ticket number, like 4821.",
 * "Wrong PIN", "Only a TA can do that."
 *
 * @author Ha Minh Nguyen
 * @version 2026.11.13
 */
public class LineController {

    private final OfficeHoursLine model;
    private String taPin; // null until setTaPin succeeds, then never changes
    private boolean taMode;

    /**
     * Stores the model. TA mode starts off and no PIN is set.
     *
     * @param model
     *            the line
     * @throws IllegalArgumentException
     *             if model is null
     */
    public LineController(OfficeHoursLine model) {
        if (model == null) {
            throw new IllegalArgumentException("Model must not be null.");
        }
        this.model = model;
        taPin = null;
        taMode = false;
    }


    /**
     * Sets the session's TA PIN. Called once at startup by TaView.
     *
     * @param pin
     *            4 to 8 digits
     * @return ok, or fail if the PIN is not 4 to 8 digits (or null) or a
     *         PIN was already set (PIN unchanged)
     */
    public ActionResult setTaPin(String pin) {
        if (taPin != null) {
            return ActionResult.fail("The TA PIN is already set.");
        }
        if (pin == null || !pin.matches("\\d{4,8}")) {
            return ActionResult.fail("Enter a PIN with 4 to 8 digits.");
        }
        taPin = pin;
        return ActionResult.ok("TA PIN set.");
    }


    /**
     * A student joins.
     *
     * @param name
     *            what they typed for their name
     * @param question
     *            what they typed for their question
     * @return ok "You're #4. Your ticket is 4821.", or fail with the
     *         model's message
     */
    public ActionResult join(String name, String question) {
        try {
            int ticket = model.join(name, question);
            return ActionResult.ok("You're #" + model.positionOf(ticket)
                + ". Your ticket is " + ticket + ".");
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }


    /**
     * A student leaves early.
     *
     * @param ticketText
     *            what they typed for their ticket
     * @return ok, or fail "Enter your ticket number, like 4821." if it is
     *         not a number, or fail with the model's message if no such
     *         ticket is waiting
     */
    public ActionResult leave(String ticketText) {
        if (ticketText == null) {
            return ActionResult.fail("Enter your ticket number, like 4821.");
        }
        try {
            int ticket = Integer.parseInt(ticketText.trim());
            model.leave(ticket);
            return ActionResult.ok("You left the line.");
        }
        catch (NumberFormatException e) {
            return ActionResult.fail("Enter your ticket number, like 4821.");
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }


    /**
     * Turns TA mode on if the PIN matches.
     *
     * @param pin
     *            what was typed
     * @return ok, or fail "Wrong PIN" (TA mode stays off) if it is wrong,
     *         null, or no PIN was ever set
     */
    public ActionResult taLogin(String pin) {
        taMode = taPin != null && taPin.equals(pin);
        if (!taMode) {
            return ActionResult.fail("Wrong PIN");
        }
        return ActionResult.ok("TA logged in.");
    }


    /**
     * Turns TA mode off. Safe to call when already off.
     */
    public void taLogout() {
        taMode = false;
    }


    /**
     * Returns whether a TA is logged in.
     *
     * @return true in TA mode
     */
    public boolean isTaMode() {
        return taMode;
    }


    /**
     * TA calls the next student.
     *
     * @return ok naming who is now being helped (read it from
     *         model.getSnapshot().getNowHelping().getName()), fail "Only a
     *         TA can do that." if not in TA mode, or fail with the model's
     *         message
     */
    public ActionResult callNext() {
        if (!taMode) {
            return ActionResult.fail("Only a TA can do that.");
        }
        try {
            model.callNext();
            return ActionResult.ok("Now helping: "
                + model.getSnapshot().getNowHelping().getName());
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }


    /**
     * TA finishes with the current student.
     *
     * @return same pattern as callNext
     */
    public ActionResult finishCurrent() {
        if (!taMode) {
            return ActionResult.fail("Only a TA can do that.");
        }
        try {
            model.finishCurrent();
            return ActionResult.ok("Finished helping the current student.");
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }


    /**
     * TA puts the current student back at the front.
     *
     * @return same pattern as callNext
     */
    public ActionResult putBack() {
        if (!taMode) {
            return ActionResult.fail("Only a TA can do that.");
        }
        try {
            model.putBack();
            return ActionResult.ok("Student put back at the front.");
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }


    /**
     * TA closes the line. On success, also turns TA mode off.
     *
     * @return same pattern as callNext; the ok message can include the
     *         final stats from model.getSnapshot()
     */
    public ActionResult closeLine() {
        if (!taMode) {
            return ActionResult.fail("Only a TA can do that.");
        }
        try {
            model.closeLine();
            taMode = false;
            return ActionResult.ok("The line is closed.");
        }
        catch (LineRuleException e) {
            return ActionResult.fail(e.getMessage());
        }
    }
}