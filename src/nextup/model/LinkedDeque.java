package nextup.model;

import java.util.ArrayList;
import java.util.List;
import java.util.NoSuchElementException;

/**
 *
 * A doubly linked deque with two sentinel nodes. head and tail are dummy
 * nodes that never hold data and are never removed. Real nodes live between
 * them:
 *
 * Big-O, where n is the number of entries: everything is O(1) except
 * remove (O(n) to find, O(1) to unlink) and toList (O(n)).
 *
 * @author Nicolas Marchese (nmarchese)
 * @version 2026.11.08
 *
 * @param <T>
 *            the type of entry stored
 */
public class LinkedDeque<T> {

    private final Node<T> head; // front sentinel, holds no data
    private final Node<T> tail; // back sentinel, holds no data
    private int size;

    /**
     * Creates an empty deque: two sentinels linked to each other.
     */
    public LinkedDeque() {
        head = new Node<T>(null);
        tail = new Node<T>(null);
        head.next = tail;
        tail.prev = head;
        size = 0;
    }


    /**
     * Adds an entry at the back. O(1)
     *
     * @param entry
     *            the entry to add
     * @throws IllegalArgumentException
     *             if entry is null (deque unchanged)
     */
    public void enqueue(T entry) {
        if (entry == null) {
            throw new IllegalArgumentException("Entry must not be null.");
        }
        Node<T> node = new Node<T>(entry);
        node.prev = tail.prev;
        node.next = tail;
        tail.prev.next = node;
        tail.prev = node;
        size++;
    }


    /**
     * Removes and returns the front entry. O(1)
     *
     * @return the front entry
     * @throws NoSuchElementException
     *             if the deque is empty
     */
    public T dequeue() {
        if (isEmpty()) {
            throw new NoSuchElementException("Deque is empty.");
        }
        Node<T> first = head.next;
        head.next = first.next;
        first.next.prev = head;
        size--;
        return first.data;
    }


    /**
     * Returns the front entry without removing it. O(1)
     *
     * @return the front entry
     * @throws NoSuchElementException
     *             if the deque is empty
     */
    public T peek() {
        if (isEmpty()) {
            throw new NoSuchElementException("Deque is empty.");
        }
        return head.next.data;
    }


    /**
     * Returns whether the deque is empty. O(1)
     *
     * @return true if there are no entries
     */
    public boolean isEmpty() {
        return size == 0;
    }


    /**
     * Returns the number of entries. O(1)
     *
     * @return the size
     */
    public int size() {
        return size;
    }


    /**
     * Adds an entry at the FRONT. Used to put a student back. O(1)
     *
     * @param entry
     *            the entry to add
     * @throws IllegalArgumentException
     *             if entry is null (deque unchanged)
     */
    public void addToFront(T entry) {
        if (entry == null) {
            throw new IllegalArgumentException("Entry must not be null.");
        }
        Node<T> node = new Node<T>(entry);
        node.prev = head;
        node.next = head.next;
        head.next.prev = node;
        head.next = node;
        size++;
    }


    /**
     * Removes the first entry equal to the given one (using equals). O(n)
     * to find it, O(1) to unlink. Used when a student leaves early.
     *
     * @param entry
     *            the entry to remove
     * @return true if it was found and removed; false if entry is null, not
     *         found, or the deque is empty (deque unchanged)
     */
    public boolean remove(T entry) {
        if (entry == null) {
            return false;
        }
        for (Node<T> current = head.next; current != tail; current =
            current.next) {
            if (current.data.equals(entry)) {
                current.prev.next = current.next;
                current.next.prev = current.prev;
                size--;
                return true;
            }
        }
        return false;
    }


    /**
     * Returns a NEW list of the entries, front first. Changing the list
     * does not change the deque. O(n)
     *
     * @return the entries; an empty list (never null) if the deque is empty
     */
    public List<T> toList() {
        List<T> entries = new ArrayList<T>();
        for (Node<T> current = head.next; current != tail; current =
            current.next) {
            entries.add(current.data);
        }
        return entries;
    }

    /**
     * One node of the deque. Sentinels have null data.
     *
     * @param <E>
     *            the type of data
     */
    private static class Node<E> {
        private final E data;
        private Node<E> prev;
        private Node<E> next;

        /**
         * Creates an unlinked node.
         *
         * @param data
         *            the data, or null for a sentinel
         */
        Node(E data) {
            this.data = data;
            prev = null;
            next = null;
        }
    }
}
